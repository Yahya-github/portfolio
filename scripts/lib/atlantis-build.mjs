// Pure helpers for scripts/export-atlantis.mjs: measure an exported Godot web
// build and render content/generated/atlantis-build.ts (PROOF-01, D-10).
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";

const BYTES_PER_MB = 1_000_000;

const gzip9 = (buf) => gzipSync(buf, { level: 9 }).length;
const brotli5 = (buf) =>
  brotliCompressSync(buf, { params: { [constants.BROTLI_PARAM_QUALITY]: 5 } })
    .length;

/** Decimal megabytes with one decimal: 23456789 -> "23.5". */
export function formatMB(bytes) {
  return (bytes / BYTES_PER_MB).toFixed(1);
}

/**
 * Sizes of play.wasm / play.pck / play.js in `dir`. totalBytes is conservative:
 * the pck is counted raw because it is mostly incompressible media.
 */
export function measureBuild(dir, version) {
  const wasm = readFileSync(join(dir, "play.wasm"));
  const pck = readFileSync(join(dir, "play.pck"));
  const js = readFileSync(join(dir, "play.js"));
  const wasmGzip = gzip9(wasm);
  const jsGzip = gzip9(js);
  const totalBytes = wasmGzip + pck.length + jsGzip;
  return {
    version,
    path: `/games/atlantis/${version}/play.html`,
    wasmRaw: wasm.length,
    wasmGzip,
    wasmBrotli5: brotli5(wasm),
    pck: pck.length,
    jsGzip,
    totalBytes,
    totalMB: formatMB(totalBytes),
  };
}

const HEADER =
  "// GENERATED by scripts/export-atlantis.mjs (pnpm game:export). Do not edit by hand.\n" +
  'import type { AtlantisBuild } from "../types";\n\n';

/** TypeScript source of content/generated/atlantis-build.ts. */
export function renderBuildModule(build) {
  if (build === null) {
    return `${HEADER}export const atlantisBuild: AtlantisBuild | null = null;\n`;
  }
  const lines = [
    `  version: ${JSON.stringify(build.version)},`,
    `  path: ${JSON.stringify(build.path)},`,
    `  wasmRaw: ${build.wasmRaw},`,
    `  wasmGzip: ${build.wasmGzip},`,
    `  wasmBrotli5: ${build.wasmBrotli5},`,
    `  pck: ${build.pck},`,
    `  jsGzip: ${build.jsGzip},`,
    `  totalBytes: ${build.totalBytes},`,
    `  totalMB: ${JSON.stringify(build.totalMB)},`,
  ];
  return `${HEADER}export const atlantisBuild: AtlantisBuild | null = {\n${lines.join("\n")}\n};\n`;
}
