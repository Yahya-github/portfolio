// PROOF-01: measured size data behind the Atlantis size line (never typed).
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";
import { afterEach, describe, expect, it } from "vitest";
import {
  formatMB,
  measureBuild,
  renderBuildModule,
} from "../scripts/lib/atlantis-build.mjs";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

function fixture(): { dir: string; wasm: Buffer; pck: Buffer; js: Buffer } {
  const dir = mkdtempSync(join(tmpdir(), "atlantis-build-"));
  dirs.push(dir);
  const wasm = Buffer.from("wasm-bytes ".repeat(500));
  const pck = Buffer.from("pck-bytes-".repeat(40));
  const js = Buffer.from("function engine(){return 1}".repeat(30));
  writeFileSync(join(dir, "play.wasm"), wasm);
  writeFileSync(join(dir, "play.pck"), pck);
  writeFileSync(join(dir, "play.js"), js);
  return { dir, wasm, pck, js };
}

describe("measureBuild", () => {
  it("returns raw, gzip -9 and brotli q5 sizes with a conservative total", () => {
    const { dir, wasm, pck, js } = fixture();
    const wasmGzip = gzipSync(wasm, { level: 9 }).length;
    const jsGzip = gzipSync(js, { level: 9 }).length;
    const wasmBrotli5 = brotliCompressSync(wasm, {
      params: { [constants.BROTLI_PARAM_QUALITY]: 5 },
    }).length;

    const build = measureBuild(dir, "abc123def456");

    expect(build.version).toBe("abc123def456");
    expect(build.path).toBe("/games/atlantis/abc123def456/play.html");
    expect(build.wasmRaw).toBe(wasm.length);
    expect(build.wasmGzip).toBe(wasmGzip);
    expect(build.wasmBrotli5).toBe(wasmBrotli5);
    expect(build.pck).toBe(pck.length);
    expect(build.jsGzip).toBe(jsGzip);
    expect(build.totalBytes).toBe(wasmGzip + pck.length + jsGzip);
    expect(build.totalMB).toBe(formatMB(build.totalBytes));
  });
});

describe("formatMB", () => {
  it("formats decimal megabytes with one decimal", () => {
    expect(formatMB(23_456_789)).toBe("23.5");
    expect(formatMB(0)).toBe("0.0");
  });
});

describe("renderBuildModule", () => {
  it("renders a null module before any export exists", () => {
    const src = renderBuildModule(null);
    expect(src).toContain("GENERATED by scripts/export-atlantis.mjs");
    expect(src).toContain(
      "export const atlantisBuild: AtlantisBuild | null = null;",
    );
  });

  it("renders every field of a measured build", () => {
    const { dir } = fixture();
    const build = measureBuild(dir, "abc123def456");
    const src = renderBuildModule(build);
    expect(src).toContain("GENERATED by scripts/export-atlantis.mjs");
    for (const key of Object.keys(build)) expect(src).toContain(key);
    expect(src).toContain(`totalMB: "${build.totalMB}"`);
  });
});
